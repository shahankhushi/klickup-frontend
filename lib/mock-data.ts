function daysFromToday(offset: number) {
  const date = new Date();
  date.setHours(12, 0, 0, 0);
  date.setDate(date.getDate() + offset);
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function atDay(offset: number, hours: number, minutes = 10) {
  const date = new Date();
  date.setHours(hours, minutes, 0, 0);
  date.setDate(date.getDate() + offset);
  return date.toISOString();
}

function check(id: string, title: string, done = false): ChecklistItem {
  return { id, title, done };
}

function comment(id: string, authorId: string, body: string, day: number, hour: number): Comment {
  return { id, authorId, body, createdAt: atDay(day, hour, 18) };
}

function event(id: string, text: string, day: number, hour: number): ActivityEvent {
  return { id, text, createdAt: atDay(day, hour, 6) };
}

